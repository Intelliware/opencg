-- The application connects as the single role the image creates from
-- POSTGRES_USER (OPENCG__POSTGRES__USER, default `opencg`), which also runs these
-- init scripts, hence CURRENT_USER rather than a hard-coded role name.
GRANT USAGE ON SCHEMA opencg TO CURRENT_USER;
GRANT SELECT, INSERT, UPDATE ON ALL TABLES IN SCHEMA opencg TO CURRENT_USER;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA opencg TO CURRENT_USER;

ALTER DEFAULT PRIVILEGES IN SCHEMA opencg
  GRANT SELECT, INSERT, UPDATE ON TABLES TO CURRENT_USER;
ALTER DEFAULT PRIVILEGES IN SCHEMA opencg
  GRANT USAGE, SELECT ON SEQUENCES TO CURRENT_USER;

-- AGE graph access.
GRANT USAGE ON SCHEMA ag_catalog TO CURRENT_USER;
GRANT SELECT ON ALL TABLES IN SCHEMA ag_catalog TO CURRENT_USER;
